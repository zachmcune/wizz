// LOBBY MODEL — create/join, slot claiming, ready state, and AI fill-in.
//
// This is the transport-free half of the Phase 6 lobby: it owns the rules and the messages, and knows nothing
// about WebSockets. That split is what lets the whole lobby flow be tested in milliseconds without a socket
// (`tests/net/lobby.test.ts`), and it is also what lets the same logic back the browser UI.
//
// IT SPEAKS THE RELAY'S PROTOCOL RATHER THAN A NEW ONE. The relay (`relay/relay-app.mjs`) is unchanged v1 code
// and already implements claiming, ready states, start validation and AI slots; re-implementing those rules
// would mean maintaining two versions of "is this lobby startable" that could disagree. So this class mirrors
// the relay's rules and `tests/net/lobby.test.ts` asserts the same decisions the relay's own suite does.
//
// AI FILL-IN is a lobby-level concept, not a network one: a slot marked `ai` never needs a connection, and every
// client spawns it locally. That is why an "empty" seat still produces a real opponent in a 4-player match with
// two humans.

import type { LobbySlotWire, LobbyStateWire, ClientMessage } from './protocol';

export type Difficulty = 'easy' | 'normal' | 'hard';

export interface LobbyOptions {
  mapId: string;
  /** How many slots the match exposes (2 to 4). Slots beyond `players` are `closed`. */
  slots?: number;
  /** Room code. Generated by `createRoomCode()` when the player creates a lobby. */
  room?: string;
}

/** Four canonical team colours, matched to the sim's palette so a lobby chip and a unit read the same. */
const COLORS = ['#4f9dff', '#ff5d5d', '#5cff8a', '#ffd166'];

/**
 * A short, unambiguous room code.
 *
 * The alphabet omits `0/O` and `1/I/L` because the code is read aloud and typed on a phone keyboard, and a
 * misheard character is the most common reason a join fails. The relay upper-cases whatever it receives
 * (`String(msg.room).toUpperCase()`), so the code is generated upper-case to match.
 */
export function createRoomCode(random: () => number): string {
  const alphabet = 'ABCDEFGHJKMNPQRSTUVWXYZ23456789';
  let out = '';
  for (let i = 0; i < 5; i++) out += alphabet[Math.floor(random() * alphabet.length)] ?? 'A';
  return out;
}

/**
 * Build the initial lobby state a host publishes.
 *
 * Slot 0 is the host and is immediately claimed and ready. Every additional slot starts `open` so a joining
 * player can take it, which is what makes "create a lobby, send the code, friend joins" work without the host
 * having to configure anything first.
 */
export function createLobby(opts: LobbyOptions): LobbyStateWire {
  const count = Math.min(4, Math.max(2, opts.slots ?? 2));
  const slots: LobbySlotWire[] = [];
  for (let i = 0; i < 4; i++) {
    const active = i < count;
    slots.push({
      id: `player${i}`,
      kind: i === 0 ? 'human' : active ? 'open' : 'closed',
      team: String(i),
      color: COLORS[i]!,
      startIndex: active ? i : null,
      factionId: 'arcane',
      claimedBy: null,
      ready: false,
    });
  }
  return { mapId: opts.mapId, factionId: 'arcane', slots };
}

/** Slots that will actually spawn a player. */
export function activeSlots(state: LobbyStateWire): LobbySlotWire[] {
  return state.slots.filter((s) => s.kind !== 'closed');
}

/** Slots a human must occupy before the match can start. `ai` and `closed` are not among them. */
export function requiredHumanSlots(state: LobbyStateWire): LobbySlotWire[] {
  return state.slots.filter((s) => s.kind === 'human' || s.kind === 'open');
}

export interface StartCheck {
  ok: boolean;
  /** A player-facing reason, empty when `ok`. */
  reason: string;
}

/**
 * Can this lobby start?
 *
 * Mirrors the relay's `tryStartMatch` rules exactly, and adds the one it does not need because the UI here can
 * satisfy it: a slot marked `open` that nobody claimed is converted to AI fill-in by the host rather than being
 * a blocker. That is the brief's "AI fill-in for empty slots" requirement, and doing it at start time means the
 * host never has to toggle a dropdown before playing.
 */
export function canStart(state: LobbyStateWire): StartCheck {
  const active = activeSlots(state);
  if (active.length < 2) return { ok: false, reason: 'A match needs at least two players.' };

  const corners = new Set<number>();
  for (const slot of active) {
    if (slot.startIndex === null) return { ok: false, reason: 'Every player needs a starting position.' };
    if (corners.has(slot.startIndex)) return { ok: false, reason: 'Every player needs a unique starting position.' };
    corners.add(slot.startIndex);
  }

  for (const slot of requiredHumanSlots(state)) {
    if (!slot.claimedBy) return { ok: false, reason: 'Waiting for all players to join.' };
    if (!slot.ready) return { ok: false, reason: 'Not all players are ready.' };
  }
  return { ok: true, reason: '' };
}

/**
 * Fill every unclaimed open slot with an AI, so the host can start without waiting.
 *
 * Returns a NEW state; the input is not mutated, because the lobby renders from the old one while the message
 * is in flight and a torn state would flicker.
 */
export function fillEmptyWithAi(state: LobbyStateWire, difficulty: Difficulty = 'normal'): LobbyStateWire {
  const slots = state.slots.map((s) => {
    if (s.kind !== 'open' || s.claimedBy) return s;
    return { ...s, kind: 'ai' as const, ready: true, aiDifficulty: difficulty, claimedBy: null };
  });
  return { ...state, slots };
}

/**
 * Assign the lowest free spawn corner to a slot.
 *
 * The relay does this too (`assignAvailableStartIndex`); duplicating the rule here keeps the lobby's local view
 * consistent with what the relay will broadcast, so the UI does not visibly re-shuffle after a claim round trip.
 */
export function assignCorner(state: LobbyStateWire, slotId: string): LobbyStateWire {
  const taken = new Set(
    state.slots.filter((s) => s.id !== slotId && s.kind !== 'closed' && s.startIndex !== null).map((s) => s.startIndex!),
  );
  const slots = state.slots.map((s) => {
    if (s.id !== slotId) return s;
    if (s.startIndex !== null && !taken.has(s.startIndex)) return s;
    for (let i = 0; i < 4; i++) {
      if (!taken.has(i)) return { ...s, startIndex: i };
    }
    return { ...s, startIndex: null };
  });
  return { ...state, slots };
}

/**
 * Apply a server message to the local lobby state.
 *
 * Returns the new state and, when the message is the one that starts the match, the seed and start tick. Keeping
 * this a pure function of (state, message) means the browser UI, the tests and any future headless client all
 * interpret the wire identically.
 */
export interface LobbyTransition {
  state: LobbyStateWire;
  matchStart?: { seed: number; startTick: number };
  /** Human-readable event for the UI's status line. */
  note?: string;
}

export function applyServerMessage(state: LobbyStateWire, msg: Record<string, unknown>): LobbyTransition {
  switch (msg.t) {
    case 'lobbyState': {
      const next = msg.state as LobbyStateWire | undefined;
      return next ? { state: next } : { state };
    }
    case 'waiting': {
      const count = Number(msg.playerCount ?? 0);
      const max = Number(msg.maxPlayers ?? 0);
      return { state, note: `${count} of ${max} players connected` };
    }
    case 'peerJoined':
      return { state, note: 'A player joined' };
    case 'peerLeft':
      return { state, note: 'A player left' };
    case 'peerDisconnected':
      return { state, note: 'A player disconnected' };
    case 'matchStart': {
      const next = msg.state as LobbyStateWire | undefined;
      return {
        state: next ?? state,
        matchStart: { seed: Number(msg.seed ?? 0), startTick: Number(msg.startTick ?? 0) },
        note: 'Match starting',
      };
    }
    case 'error':
      return { state, note: String(msg.message ?? 'The relay reported an error') };
    case 'joined': {
      const next = msg.lobbyState as LobbyStateWire | undefined;
      return { state: next ?? state, note: 'Joined the lobby' };
    }
    default:
      return { state };
  }
}

// ────────────────────────────────────────────────────────────── outbound messages

/** The message a player sends to create a room. The first `join` for a code makes that player the host. */
export function joinMessage(room: string, lobby?: LobbyStateWire): ClientMessage {
  return lobby ? { t: 'join', room: room.toUpperCase(), lobbyState: lobby } : { t: 'join', room: room.toUpperCase() };
}

/** Rejoin an in-progress match using the connection id from the original join. */
export function rejoinMessage(room: string, connId: string): ClientMessage {
  return { t: 'rejoin', room: room.toUpperCase(), connId };
}

export function claimMessage(slotId: string, startIndex: number | null, factionId: string): ClientMessage {
  return { t: 'claimSlot', slotId, team: slotId, color: COLORS[0]!, startIndex, factionId };
}

export function readyMessage(slotId: string, ready: boolean): ClientMessage {
  return { t: 'slotReady', slotId, ready };
}

export function startMessage(): ClientMessage {
  return { t: 'startMatch' };
}

export function lobbyUpdateMessage(state: LobbyStateWire): ClientMessage {
  return { t: 'lobbyUpdate', state };
}
